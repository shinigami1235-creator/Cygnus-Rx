// cls: drug class          dup: class name for the same-class warning
// tags: words the interaction list matches on (the generic name is added)
// uses: on the label       off: off-label but in common use
// cover: antibacterial spectrum, 2 good, 1 some or variable, 0 none
//        gp gram-positive, gn gram-negative, aty atypicals, ana anaerobes,
//        mrsa, pseu Pseudomonas
// bugs: organisms worth naming   virus, fungi, parasites: what it treats
// preg, lact: [level, text], level 'ok', 'caution' or 'avoid'
// kidney: dose change in kidney disease   no: do not use when
// watch: side effects and advice          kids: children's dosing
// child: [months, level, text], a warning under that age
// ped: weight dose for liquids, see childDose()
// s2: a dangerous drug under RA 9165, needs an S2 license
// allergy: allergy words that mean avoid   a: other names, brands
// topical: changes for the cream, gel or ointment of the same generic
// oral: changes for a tablet of a generic the starter list has as a cream.
//       A cream-only entry with no oral part has no card for a tablet.

