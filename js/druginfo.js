const LOCAL = ['topical', 'vaginal', 'eye', 'ear'];

// True when every starter form of this generic goes on the skin, so the
// entry says nothing true about a tablet.
function localOnly(k, i) {
  const names = [k, ...(i.a || [])];
  const rows = DRUGS.filter(d => names.includes(d.g.toLowerCase()));
  return rows.length > 0 && rows.every(d => LOCAL.includes(d.r));
}

// The stored entry for a medicine, with the topical changes laid over it
// for a cream, gel or ointment.
export function infoFor(generic, route) {
  const key = String(generic || '').trim().toLowerCase();
  if (!key) return null;
  let k = INFO[key] ? key : Object.keys(INFO).find(x => (INFO[x].a || []).includes(key));
  if (!k) return null;
  const i = INFO[k];
  const local = LOCAL.includes(route);
  if (local) return i.topical ? { ...i, ...i.topical, key: k, local: true } : { ...i, key: k };
  if (i.oral) return { ...i, ...i.oral, key: k };
  if (localOnly(k, i)) return null;
  return { ...i, key: k };
}

// Names in free text, such as the patient's regular medicines, matched to entries.
export function findNames(text) {
  const t = ' ' + String(text || '').toLowerCase().replace(/[^a-z0-9+-]+/g, ' ') + ' ';
  return Object.keys(INFO).filter(k => [k, ...(INFO[k].a || [])].some(n => t.includes(' ' + n.replace(/[^a-z0-9+-]+/g, ' ').trim() + ' ')));
}
